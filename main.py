# 1: Напиши програму, яка приймає від користувача рядок та повертає його в оберненому порядку з використанням службового символу \n.
text = input("Введіть рядок: ")
reverse_text = text[::-1]
print(f"Обернений рядок: {reverse_text}\n")


# 2: Напиши програму, що приймає числа від 1 до 10 та виводить їх на екран з використанням форматування f-string, додавши символ нового рядка \n після кожного числа.
print("Числа від 1 до 10:")
for i in range(1, 11):
    print(f"{i}\n", end="")


